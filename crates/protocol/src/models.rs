#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn product_ids_are_unique() {
        let mut pids: Vec<u16> = MODELS.iter().map(|m| m.pid).collect();
        pids.sort_unstable();
        pids.dedup();
        assert_eq!(pids.len(), MODELS.len());
    }

    #[test]
    fn every_model_has_a_picture() {
        for m in MODELS {
            assert!(m.image_url().is_some_and(|u| u.starts_with("https://")), "{}", m.name);
        }
    }

    #[test]
    fn rates_and_ranges_are_sane() {
        for m in MODELS {
            assert!(m.poll.rates().windows(2).all(|w| w[0] < w[1]), "{}", m.name);
            assert!(m.dpi == DpiRange::None || m.dpi.max() >= DpiRange::MIN, "{}", m.name);
        }
    }
}
